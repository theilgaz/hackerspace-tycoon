import type { MachineType, PartData, ProjectDef, StageKey } from '@/game/types';

type Part = Omit<PartData, 'id' | 'status' | 'attempts'>;

/** Printed part shorthand: name, machine-hours, grams. */
function fdm(name: string, hours: number, material: number): Part {
  return { name, machineType: 'fdm', hours, material };
}
/** Machined part — no filament, needs a CNC in the space. */
function cnc(name: string, hours: number): Part {
  return { name, machineType: 'cnc', hours, material: 0 };
}
function repeat(count: number, make: (index: number) => Part): Part[] {
  return Array.from({ length: count }, (_, i) => make(i + 1));
}

