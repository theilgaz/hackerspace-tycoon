export const CATALOG: ProjectDef[] = CATALOG_DATA;

export const CATALOG_MAP: Record<string, ProjectDef> = Object.fromEntries(
  CATALOG.map((def) => [def.id, def]),
);

export function catalogForEra(era: number): ProjectDef[] {
  return CATALOG.filter((def) => def.era <= era);
}

/** Can the space physically attempt this yet? */
export function canBuild(def: ProjectDef, owned: MachineType[]): boolean {
  return def.requires.every((type) => owned.includes(type));
}

export function missingMachines(def: ProjectDef, owned: MachineType[]): MachineType[] {
  return def.requires.filter((type) => !owned.includes(type));
}
